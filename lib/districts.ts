export function districtPlace(key: string): Place | null {
  const [gi, di] = key.split(':').map(Number);
  const g = DISTRICTS[gi];
  const d = g?.items[di];
  if (!d) return null;
  return { name: `${g.group === 'กรุงเทพมหานคร' ? 'เขต' : 'อ.'}${d[0]} ${g.group}`, lat: d[1], lng: d[2], key };
}

/** หาเขต/อำเภอที่ใกล้พิกัดที่สุด (ใช้ตั้งชื่อตำแหน่ง GPS) */
export function nearestDistrict(lat: number, lng: number) {
  let best: { key: string; name: string; d: number } | null = null;
  DISTRICTS.forEach((g, gi) =>
    g.items.forEach(([name, la, ln], di) => {
      const d = Math.hypot((la - lat) * 111, (ln - lng) * 108);
      if (!best || d < best.d) best = { key: `${gi}:${di}`, name: `${g.group === 'กรุงเทพมหานคร' ? 'เขต' : 'อ.'}${name}`, d };
    }),
  );
  return best as { key: string; name: string; d: number } | null;
}
