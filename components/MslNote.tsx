/** อธิบายหน่วย ม.รทก. (เมตรเหนือระดับน้ำทะเลปานกลาง) แบบกดเปิดอ่าน */
export default function MslNote({ example }: { example?: { name: string; wall: number; water: number } }) {
  return (
    <details className="msl-note">
      <summary>ม.รทก. คืออะไร?</summary>
      <p>
        <b>ม.รทก.</b> ย่อมาจาก <b>เมตร เหนือระดับน้ำทะเลปานกลาง</b> (m MSL) คือวัดความสูงจากระดับเฉลี่ยของน้ำทะเลระหว่างน้ำขึ้นกับน้ำลง
        โดยประเทศไทยใช้หมุดอ้างอิงที่เกาะหลัก จ.ประจวบคีรีขันธ์ เป็นจุด 0
      </p>
      <p>
        ตัวเลขนี้<b>ไม่ใช่ความสูงจากพื้นดิน</b> เช่น คันกั้นน้ำ +3.50 ม.รทก. คือสันคันอยู่สูงกว่าระดับทะเล 3.50 ม.
        ตัวคันจริงอาจสูงจากพื้นแค่ 1–2 ม. เพราะพื้นดินกรุงเทพฯ สูงกว่าระดับทะเลไม่มาก (เฉลี่ยราว 1–1.5 ม. บางจุดต่ำกว่านั้น)
      </p>
      <p>
        ข้อดีคือระดับน้ำ ตลิ่ง และคันกั้นน้ำ ใช้จุด 0 เดียวกัน จึงลบกันได้ตรง ๆ
        {example && (
          <> เช่น ที่{example.name} คันกั้นน้ำ {example.wall.toFixed(2)} − น้ำ {example.water.toFixed(2)} = น้ำต่ำกว่าคัน <b>{(example.wall - example.water).toFixed(2)} ม.</b></>
        )}
      </p>
    </details>
  );
}
